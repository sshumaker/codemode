#!/usr/bin/env node
/**
 * Put a real agent in front of the jobs primitives and record what it does.
 *
 *   node runtime/eval/run.mjs <env-file> <task> [--model ...] [--timeout 300]
 *
 * This is the direct-inspection loop. Everything else in runtime/ is unit-tested
 * against a mocked clock, which proves the state machine and proves nothing about
 * whether an agent that has never seen this API can pick it up from the prompt, the
 * docs and the errors. That question can only be answered by reading trajectories.
 *
 * Wires all four channels the model can learn from:
 *
 *   system prompt   `jobs.PROMPT`, generated by `jobs.py --prompt`
 *   api listing     api/jobs.md, generated by `jobs.py --docs`
 *   kernel prelude  imports `jobs`, guards sleep/threads, announces prior jobs
 *   errors          the guards, and the cell-timeout interrupt
 *
 * Generated rather than copied, so none of them can drift from the implementation.
 */
import { spawn, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync, existsSync, createWriteStream } from "node:fs";
import { dirname, join } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { TASKS } from "./tasks.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const RUNTIME = join(ROOT, "runtime");
const CLI = join(ROOT, "vendor/prime-agent/packages/coding-agent/dist/cli.js");

const argv = process.argv.slice(2);
const flag = (n, d) => {
	const i = argv.indexOf(`--${n}`);
	return i >= 0 ? argv[i + 1] : d;
};
const positional = argv.filter((a, i) => !a.startsWith("--") && !(i > 0 && argv[i - 1].startsWith("--")));
const [envFile, taskName] = positional;

if (!envFile || !taskName) {
	console.error(`usage: runtime/eval/run.mjs <env-file> <task> [--model M] [--timeout S]`);
	console.error(`tasks: ${Object.keys(TASKS).join(", ")}`);
	process.exit(2);
}
const task = TASKS[taskName];
if (!task) {
	console.error(`unknown task ${taskName}. have: ${Object.keys(TASKS).join(", ")}`);
	process.exit(2);
}

const model = flag("model", "anthropic/claude-opus-5");
const timeoutSec = Number(flag("timeout", "420"));
const runId = flag("run-id", `${taskName}__${Date.now()}`);
const runDir = join(ROOT, ".run/jobs", runId);
mkdirSync(runDir, { recursive: true });

/** Generated from the module, never transcribed — see jobs.py's __main__. */
function emit(kind) {
	const r = spawnSync("python3", [join(RUNTIME, "jobs.py"), `--${kind}`], { encoding: "utf8" });
	if (r.status !== 0) throw new Error(`jobs.py --${kind} failed: ${r.stderr}`);
	return r.stdout;
}

// --- the four channels ---------------------------------------------------------

// 1. api listing, discovered the same way the agent discovers everything else.
mkdirSync(join(runDir, "api"), { recursive: true });
writeFileSync(join(runDir, "api/jobs.md"), emit("docs"));

// 2. kernel prelude, via an IPython startup file. IPython executes everything in
//    profile_default/startup/ in lexical order before the first cell, which is the
//    hook that makes `jobs` present without an import.
const ipythonDir = join(runDir, "ipython");
const startupDir = join(ipythonDir, "profile_default/startup");
mkdirSync(startupDir, { recursive: true });
writeFileSync(
	join(startupDir, "00-jobs.py"),
	`import runpy, sys\nsys.path.insert(0, ${JSON.stringify(RUNTIME)})\n` +
		`runpy.run_path(${JSON.stringify(join(RUNTIME, "kernel-prelude.py"))}, run_name="__prelude__")\n` +
		// run_path executes in its own namespace, so re-export what the agent needs.
		`import jobs\n`,
);

// 3. system prompt. Base is deliberately minimal — this eval is about whether the
//    jobs section lands, so nothing else should be doing the work.
const BASE = [
	"You are working in a Python (IPython) kernel via the `ipython` tool.",
	"State persists between cells. Read `api/` for available interfaces.",
	"Be concise. When the task is done, say so explicitly.",
].join(" ");
// --no-prompt drops the resident guidance, leaving only api/jobs.md and the errors.
// This is how the channel split gets tested rather than asserted: if the guards and
// the interrupt really are the strongest teacher, an agent should still find its way.
const withoutPrompt = argv.includes("--no-prompt");
const jobsPrompt = withoutPrompt ? "" : emit("prompt");
writeFileSync(join(runDir, "prompt.txt"), `${BASE}\n\n${jobsPrompt}`);

const cliArgs = [
	CLI,
	"-p",
	"--mode",
	"json",
	"--model",
	model,
	"--tools",
	"ipython",
	"--cwd",
	runDir,
	"--no-context-files",
	"--no-prompt-templates",
	"--no-extensions",
	"--system-prompt",
	BASE,
	...(jobsPrompt ? ["--append-system-prompt", jobsPrompt] : []),
	task.prompt,
];

// Task-specific fixtures (a stand-in colleague, a service that becomes ready...).
task.setup?.(runDir);

// --- run -----------------------------------------------------------------------
const jobDir = join(runDir, "jobs");
mkdirSync(jobDir, { recursive: true });

/**
 * Sandbox the REPL, not the agent — hands, not brain.
 *
 * The agent process is ours: it talks to the model API, owns a daemon socket, and
 * runs no model-authored code. Wrapping it was tried and is wrong twice over — it
 * buys no safety (nothing untrusted runs there) and it fights the daemon's own Unix
 * socket, which srt blocks by default. The kernel is the only place code the model
 * wrote actually executes, so it is the only thing that needs a boundary.
 *
 * It is also where the benchmark-integrity problem lives: `curl` to an API the MCP
 * tools wrap happens *in a cell*, not in the agent. A network allowlist on the
 * kernel is therefore the enforcement that the dead-proxy trick was approximating —
 * and on Linux it is airtight, because srt removes the network namespace entirely
 * and routes through Unix sockets, so unsetting http_proxy leaves no route at all.
 *
 * Applied by patching the kernel spawn (scripts/neutralize-prime.mjs), gated on
 * HARNESS_KERNEL_SANDBOX_SETTINGS so an unsandboxed run stays byte-identical.
 */
const sandboxed = !argv.includes("--no-sandbox");
const srtBin = join(ROOT, "node_modules/.bin/srt");
const srtSettings = join(runDir, "srt-settings.json");
if (sandboxed) {
	writeFileSync(
		srtSettings,
		`${JSON.stringify(
			{
				filesystem: {
					// Allow-only: an empty list means no write access, so the default
					// direction is the safe one. /tmp is needed by ipykernel's connection
					// files and by matplotlib/font caches.
					// os.tmpdir() rather than "/tmp": on macOS TMPDIR is a per-user
					// /var/folders/... path, and that is where ipykernel's connection file
					// lives. Allowing only /tmp left the kernel unable to reach it.
					allowWrite: [runDir, "/tmp", tmpdir()],
					denyWrite: [],
					denyRead: ["~/.ssh", "~/.aws"],
				},
				network: {
					// The kernel needs nothing off-box. Anything it reaches for is either a
					// tool-surface bypass or an accident, and both are worth recording.
					allowedDomains: [],
					deniedDomains: [],
					// ipykernel speaks ZMQ over loopback to the agent, so local binding has
					// to stay open or the kernel cannot be reached at all.
					allowLocalBinding: true,
					allowAllUnixSockets: true,
				},
			},
			null,
			2,
		)}\n`,
	);
}

/**
 * Launch through a script rather than an inline `bash -c`.
 *
 * The sandbox wrapper takes a command *string*, and this command carries a
 * multi-line system prompt and an env-file path. Quoting that into a shell string
 * correctly, twice (once for us, once for the wrapper), is exactly the kind of
 * escaping that mangled a patch earlier in this project — `\n` became a literal
 * newline. A file has no quoting problem.
 */
const shq = (x) => `'${String(x).replace(/'/g, `'"'"'`)}'`;
const launchScript = join(runDir, "launch.sh");
writeFileSync(
	launchScript,
	`#!/bin/bash\nset -a\n. ${shq(envFile)}\nset +a\nexec node ${cliArgs.map(shq).join(" ")}\n`,
	{ mode: 0o755 },
);

const started = Date.now();
const streamPath = join(runDir, "stream.jsonl");
const streamFile = createWriteStream(streamPath);
const summary = {
	turns: 0, cells: 0, cost: 0, toolCalls: 0,
	errors: [], waits: [], cellSources: [], completedCells: [], refusedCells: [],
};
let pendingCell = null;
let buffer = "";
let stderr = "";
const counted = new Set();

// The agent itself is NOT wrapped — only the kernel it spawns is (see above).
const child = spawn(
	"bash",
	[launchScript],
	{
		cwd: runDir,
		env: {
			...process.env,
			DO_NOT_TRACK: "1",
			PRIME_AGENT_TELEMETRY: "0",
			PRIME_AGENT_CODING_AGENT_DIR: join(runDir, "agent-home"),
			IPYTHONDIR: ipythonDir,
			HARNESS_JOB_DIR: jobDir,
			HARNESS_JOB_CWD: runDir,
			HARNESS_RUNTIME_DIR: RUNTIME,
			...(argv.includes("--adopt-bg") || argv.includes("--adopt-quiet") ? { HARNESS_ADOPT_BACKGROUND: "1" } : {}),
			...(argv.includes("--adopt-quiet") ? { HARNESS_ADOPT_QUIET: "1" } : {}),
			// Read by the patched kernel spawn; absent means no sandbox.
			...(sandboxed ? { HARNESS_KERNEL_SANDBOX_SETTINGS: srtSettings, HARNESS_KERNEL_SANDBOX_BIN: srtBin } : {}),
			// Deliberately low so a blocked cell is interrupted quickly and the eval
			// can observe whether the interrupt teaches `submit`.
			HARNESS_CELL_TIMEOUT_MS: String(Number(flag("cell-timeout", "60")) * 1000),
			// The floor exists to stop a wait costing a turn to save nothing; in an
			// eval it just makes every run slow, so allow shorter waits.
			HARNESS_MIN_WAIT_SECONDS: flag("min-wait", "5"),
		},
		stdio: ["ignore", "pipe", "pipe"],
	},
);

const killer = setTimeout(() => {
	summary.timedOut = true;
	child.kill("SIGKILL");
}, timeoutSec * 1000);

child.stderr.on("data", (d) => (stderr = (stderr + d).slice(-4000)));
child.stdout.on("data", (chunk) => {
	streamFile.write(chunk);
	buffer += chunk;
	const lines = buffer.split("\n");
	buffer = lines.pop() ?? "";
	for (const line of lines) {
		if (!line.startsWith("{")) continue;
		let e;
		try {
			e = JSON.parse(line);
		} catch {
			continue;
		}
		if (e.type === "tool_execution_start") {
			summary.toolCalls++;
			// The cell source is the whole point of this eval: it shows whether the
			// agent reached for jobs.* or for time.sleep/threading.
			const src = e.args?.code ?? e.args?.source ?? "";
			if (src) {
				summary.cells++;
				summary.cellSources.push(src);
				pendingCell = src;
			}
		} else if (e.type === "tool_execution_end") {
			const text = (e.result?.content ?? []).map((c) => c.text ?? "").join("\n");
			// IPython returns tracebacks as ordinary cell output, not tool errors, so
			// isError alone reported "errors 0" on a run that hit a NameError.
			const failed = e.isError || /Traceback \(most recent call last\)|^\w*Error\b/m.test(text);
			if (failed) summary.errors.push(text.slice(0, 400));
			// Pair each cell with its outcome. Anti-patterns count only in cells that
			// SUCCEEDED — a refused sleep is the guard working, not a failure. This
			// wiring was lost in an edit and only its declaration survived, so
			// completedCells stayed empty and every "no anti-pattern" verdict was
			// vacuously true. The detectorBroken assertion below exists because of it.
			if (pendingCell !== null) {
				(failed ? summary.refusedCells : summary.completedCells).push(pendingCell);
				pendingCell = null;
			}
			// The host consumes the sentinel and rewrites it, so match what the agent
			// actually receives — matching the raw sentinel silently recorded no waits
			// at all on a run that waited 90s.
			for (const m of text.matchAll(/\[waited (\d+)s outside the kernel\]/g)) {
				summary.waits.push(Number(m[1]));
			}
		} else if (e.type === "message_end" && e.message?.role === "assistant") {
			summary.turns++;
			const id = e.message.responseId;
			if (id && !counted.has(id) && e.message.usage?.totalTokens) {
				counted.add(id);
				summary.cost += e.message.usage.cost?.total ?? 0;
			}
			const texts = (e.message.content ?? []).filter((c) => c.type === "text" && c.text);
			if (texts.length) summary.finalText = texts.map((c) => c.text).join("");
		}
	}
});

/**
 * Shell sleeps that hold the kernel: a `sleep N` in the body of a %%bash cell.
 *
 * Once %%bash was un-broken, a run blocked the kernel with `%%bash\nsleep 40` twice
 * and still produced the right answer — the Python guard cannot see a subprocess
 * sleep. Nothing else catches this, so the eval has to.
 */
function blockingShellSleep(sources) {
	return sources.some((src) => {
		if (!/^\s*%%bash/.test(src)) return false;
		const body = src.replace(/^\s*%%bash[^\n]*\n/, "");
		return /(^|[;&|]|\s)sleep\s+\d/m.test(body);
	});
}

child.on("close", (code) => {
	clearTimeout(killer);
	summary.sandboxed = sandboxed;
	summary.exitCode = code;
	summary.wallMs = Date.now() - started;
	summary.stderrTail = stderr.split("\n").slice(-6).join("\n");

	// --- what the agent actually reached for ---------------------------------
	const all = summary.cellSources.join("\n");
	// What the agent actually got away with, as opposed to what it attempted.
	const done = summary.completedCells.join("\n");
	summary.used = {
		submit: /jobs\.submit\(/.test(all),
		wait: /jobs\.wait\(/.test(all),
		get: /jobs\.get\(/.test(all),
		manifest: /jobs\.(manifest|list)\(/.test(all),
		help: /jobs\.help\(/.test(all),
		expect: /expect\s*=/.test(all),
		// The anti-patterns the primitives exist to replace.
		//
		// Only a sleep the CELL performs counts. A `sleep 8` inside a submitted job's
		// command is correct and necessary — the first version of this check flagged
		// it and failed a run that had done everything right, which is the same class
		// of error as missing the real one. So: shell sleeps are counted only in
		// %%bash cells, where they block the kernel; a sleep inside a Python string
		// literal is a payload, not a pause.
		sleep: /(?:time\.|asyncio\.)?sleep\(/.test(done) || blockingShellSleep(summary.completedCells),
		shellSleep: blockingShellSleep(summary.completedCells),
		thread: /threading\.Thread|Thread\(/.test(done),
		// Attempted and refused — the guards doing their job. Reported separately
		// because it is evidence the teaching channel fired, not evidence of failure.
		guardFired: summary.refusedCells.length > 0,
	};

	// How many wrong attempts before it reached for the primitive. This is the number
	// that says whether the teaching channel works: 0 means the prompt alone carried
	// it, 1 means one guard fired and the lesson landed immediately, and a large
	// number means the error is not naming the fix clearly enough.
	const firstJobsCell = summary.cellSources.findIndex((c) => /jobs\.(submit|wait)\(/.test(c));
	summary.attemptsBeforeAdoption = firstJobsCell < 0 ? null : firstJobsCell;
	summary.guardFiresBeforeAdoption =
		firstJobsCell < 0
			? summary.refusedCells.length
			: summary.refusedCells.filter((c) => summary.cellSources.indexOf(c) < firstJobsCell).length;

	// Grade against what the task required, so a run is pass/fail rather than vibes.
	// The detector must have seen the cells it is judging. Without this, losing the
	// pairing reads as "clean run" rather than as a broken measurement.
	if (summary.cells > 0 && summary.completedCells.length + summary.refusedCells.length === 0) {
		summary.detectorBroken = true;
		console.log("!! anti-pattern detection saw 0 of " + summary.cells + " cells — results below are meaningless");
	}

	const checks = task.check({ summary, runDir, jobDir });
	summary.checks = checks;
	summary.passed = checks.every((c) => c.ok);

	writeFileSync(join(runDir, "result.json"), `${JSON.stringify({ runId, task: taskName, model, summary }, null, 2)}\n`);

	const mark = (b) => (b ? "yes" : " no");
	console.log(`\n=== ${taskName}${withoutPrompt ? " (no resident prompt)" : ""}${argv.includes("--adopt-bg") ? " [adopt-bg]" : ""} — ${summary.passed ? "PASS" : "FAIL"} ===`);
	console.log(
		`turns ${summary.turns}  cells ${summary.cells}  waits [${summary.waits.join(",")}]  ` +
			`errors ${summary.errors.length}  $${summary.cost.toFixed(3)}  ${(summary.wallMs / 1000).toFixed(0)}s` +
			`${summary.timedOut ? "  [TIMED OUT]" : ""}`,
	);
	console.log(
		`used: submit ${mark(summary.used.submit)}  wait ${mark(summary.used.wait)}  ` +
			`get ${mark(summary.used.get)}  help ${mark(summary.used.help)}  ` +
			`|  anti-patterns: sleep ${mark(summary.used.sleep)}  thread ${mark(summary.used.thread)}`,
	);
	for (const c of checks) console.log(`  ${c.ok ? "PASS" : "FAIL"}  ${c.name}${c.detail ? ` — ${c.detail}` : ""}`);
	if (summary.errors.length) {
		console.log(`\nfirst error seen by the agent:\n  ${summary.errors[0].split("\n").join("\n  ")}`);
	}
	console.log(`\n-> ${runDir}`);
	process.exit(summary.passed ? 0 : 1);
});
